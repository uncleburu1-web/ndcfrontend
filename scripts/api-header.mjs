// Prepend a "generated" header to src/api/schema.d.ts so nobody edits it by hand.
import { readFileSync, writeFileSync } from "node:fs";

const file = "src/api/schema.d.ts";
const head = "/* Generated by `npm run api:types` from api/openapi.json (spec 15 §14.3). Do not edit. */\n";
const body = readFileSync(file, "utf8");
writeFileSync(file, body.startsWith(head) ? body : head + body);
