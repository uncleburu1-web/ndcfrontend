/**
 * Spec 14 §4.9, §4.12: the web app's security headers and security.txt, built from build-time env only
 * (VITE_API_BASE_URL, VITE_CLERK_PUBLISHABLE_KEY, VITE_SECURITY_CONTACT, optional VITE_MEDIA_ORIGIN and
 * VITE_MEDIA_UPLOAD_ORIGIN). Spec 15 §15.4: with Cloudinary images (VITE_MEDIA_ORIGIN=https://res.cloudinary.com),
 * img-src allows the delivery host and connect-src allows https://api.cloudinary.com for signed browser uploads.
 *
 *   npm run headers               print the final headers (check them before deploying)
 *   npm run headers -- --write    also write deploy/_headers and deploy/nginx-security.conf
 *
 * The Vite build writes dist/_headers and dist/.well-known/security.txt with the same values.
 * Never put a secret here: only the publishable key's public Frontend API host is read.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const origin = (url) => {
  try {
    return new URL(url).origin;
  } catch {
    return "";
  }
};

/** pk_test_/pk_live_ + base64("<frontend-api-host>$") → https://<frontend-api-host> */
export function clerkFrontendApi(publishableKey = "") {
  const m = /^pk_(?:test|live)_(.+)$/.exec(publishableKey.trim());
  if (!m) return "";
  try {
    const host = Buffer.from(m[1], "base64").toString("utf8").replace(/\$$/, "");
    return /^[a-z0-9.-]+$/i.test(host) ? `https://${host}` : "";
  } catch {
    return "";
  }
}

export function buildHeaders(env = process.env) {
  const api = origin(env.VITE_API_BASE_URL ?? "") ;
  const media = origin(env.VITE_MEDIA_ORIGIN ?? "") || api;
  const onCloudinary = /(^|\.)cloudinary\.com$/.test(media ? new URL(media).hostname : "");
  const upload = origin(env.VITE_MEDIA_UPLOAD_ORIGIN ?? "") || (onCloudinary ? "https://api.cloudinary.com" : "");
  const clerk = clerkFrontendApi(env.VITE_CLERK_PUBLISHABLE_KEY ?? "");
  const challenges = "https://challenges.cloudflare.com"; // Clerk's bot protection (Turnstile)
  const clerkImages = "https://img.clerk.com";
  const join_ = (...xs) => [...new Set(xs.filter(Boolean))].join(" ");
  const csp = [
    `default-src 'self'`,
    `script-src ${join_("'self'", clerk, challenges)}`,
    `connect-src ${join_("'self'", api, clerk, upload)}`,
    `img-src ${join_("'self'", "data:", "blob:", media, clerkImages)}`,
    `frame-src ${join_(challenges)}`,
    `worker-src 'self' blob:`,
    `style-src 'self' 'unsafe-inline'`,
    `font-src 'self'`,
    `object-src 'none'`,
    `base-uri 'self'`,
    `frame-ancestors 'none'`,
    `form-action 'self'`,
  ].join("; ");
  return {
    "Content-Security-Policy": csp,
    "Strict-Transport-Security": "max-age=31536000; includeSubDomains",
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=()",
    "Cross-Origin-Opener-Policy": "same-origin",
  };
}

/** RFC 9116. Expires one year after the build. */
export function securityTxt(env = process.env, now = new Date()) {
  const contact = (env.VITE_SECURITY_CONTACT ?? "").trim();
  if (!contact) return null;
  const expires = new Date(now.getTime() + 365 * 24 * 3600 * 1000).toISOString().replace(/\.\d{3}Z$/, "Z");
  const site = origin(env.VITE_SITE_URL ?? "");
  return [
    `Contact: ${contact.includes(":") ? contact : `mailto:${contact}`}`,
    `Expires: ${expires}`,
    `Policy: ${site ? `${site}/security` : "/security"}`,
    "Preferred-Languages: en",
    "",
  ].join("\n");
}

export function headersFile(h) {
  return ["# NDCConnect web app security headers (spec 14 §4.9). Generated: npm run headers -- --write", "/*", ...Object.entries(h).map(([k, v]) => `  ${k}: ${v}`), ""].join("\n");
}

export function nginxSnippet(h) {
  return [
    "# NDCConnect web app security headers (spec 14 §4.9). Generated by `npm run headers -- --write`; include in the server block.",
    ...Object.entries(h).map(([k, v]) => `add_header ${k} "${v}" always;`),
    "",
  ].join("\n");
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const h = buildHeaders();
  for (const [k, v] of Object.entries(h)) console.log(`${k}: ${v}`);
  const txt = securityTxt();
  console.log(txt ? `\n/.well-known/security.txt:\n${txt}` : "\n(security.txt: set VITE_SECURITY_CONTACT to publish one)");
  if (process.argv.includes("--write")) {
    const root = join(dirname(fileURLToPath(import.meta.url)), "..", "deploy");
    mkdirSync(root, { recursive: true });
    writeFileSync(join(root, "_headers"), headersFile(h));
    writeFileSync(join(root, "nginx-security.conf"), nginxSnippet(h));
    console.log("\nWrote deploy/_headers and deploy/nginx-security.conf");
  }
}
